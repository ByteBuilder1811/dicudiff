"""Report generation: Markdown, self-contained HTML, and PDF (reportlab). Deterministic findings and AI
interpretations are kept in visibly separate sections."""
import html
import re
from datetime import datetime, timezone
from pathlib import Path

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models.tables import Change, Comparison, Document

ORDER = ["MODIFIED", "REMOVED", "ADDED", "NEEDS_REVIEW", "POSSIBLY_RELOCATED", "UNCHANGED"]
RISK = {"date_changed", "percentage_changed", "amount_changed", "number_changed", "legal_reference_changed", "identifier_changed", "negation_changed", "obligation_strength_changed"}
BASE_LIMITS = [
    "Changes are detected lexically and by alignment heuristics; a passage split or merged between versions may appear as MODIFIED, REMOVED or ADDED rather than a single change.",
    "Tables and multi-column layouts are extracted best-effort; check the source PDF for critical tables.",
    "AI explanations (if included) are generated by a small local model, are not legal advice, and must be verified against the quoted text.",
]


def _s(t: str | None, n: int = 600) -> str:
    t = re.sub(r"\s+", " ", t or "").strip()
    return t if len(t) <= n else t[: n - 1] + "… [truncated]"


def _loc(p, s) -> str:
    """Plain-text location. Callers must escape the result for the output format (section labels come from document headings)."""
    return "—" if p is None else f"p.{p}" + (f" §{s}" if s else "")


def _md(t: object) -> str:
    """Make untrusted text (headings, file names, labels) safe inside a Markdown table cell / inline text."""
    t = re.sub(r"\s+", " ", str(t if t is not None else "")).strip()
    return re.sub(r"([\\`*_{}\[\]<>|#])", r"\\\1", t)


def _mdt(t: object) -> str:
    """Neutralise raw HTML in free text placed in Markdown (many viewers render inline HTML)."""
    return str(t if t is not None else "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def collect(db: Session, comp: Comparison, include_unchanged: bool = False) -> dict:
    a, b = db.get(Document, comp.doc_a_id), db.get(Document, comp.doc_b_id)
    rows = db.scalars(select(Change).where(Change.comparison_id == comp.id).order_by(Change.seq)).all()
    shown = [c for c in rows if include_unchanged or c.category != "UNCHANGED"]
    counts = {c: sum(1 for r in rows if r.category == c) for c in ORDER}
    return {"comp": comp, "a": a, "b": b, "rows": shown, "counts": counts, "risk": [c for c in rows if RISK & set(c.flags or [])],
            "pending": [c for c in rows if c.review_status == "pending"], "generated": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
            "limits": list(comp.limitations or []) + BASE_LIMITS}


def _summary(d: dict) -> str:
    c, comp = d["counts"], d["comp"]
    return (f"Comparing {comp.label_a} (“{d['a'].original_name}”) with {comp.label_b} (“{d['b'].original_name}”): "
            f"{c['MODIFIED']} modified, {c['ADDED']} added, {c['REMOVED']} removed, {c['POSSIBLY_RELOCATED']} possibly relocated, "
            f"{c['NEEDS_REVIEW']} needing review, {c['UNCHANGED']} unchanged passages. "
            f"{len(d['risk'])} change(s) involve dates, numbers, amounts, negations or obligation wording and deserve priority review.")


def to_markdown(d: dict) -> str:
    comp = d["comp"]
    L = [f"# DocuDiff Comparison Report", "", f"*Generated {d['generated']} · comparison `{comp.id}` · direction: **{_md(comp.label_a)} → {_md(comp.label_b)}***", "",
         "## Executive summary", "", _mdt(_summary(d)), "", "> Findings below are **deterministic text comparisons**. Sections marked *AI interpretation* are model-generated and unverified.", "",
         "## Documents", "", f"| | File | Pages | SHA-256 |", "|---|---|---|---|",
         f"| {_md(comp.label_a)} | {_md(d['a'].original_name)} | {d['a'].page_count} | `{d['a'].sha256[:16]}…` |",
         f"| {_md(comp.label_b)} | {_md(d['b'].original_name)} | {d['b'].page_count} | `{d['b'].sha256[:16]}…` |", "",
         "## Change table", "", "| # | Category | Old location | New location | Method | Conf. | Flags |", "|---|---|---|---|---|---|---|"]
    for i, c in enumerate(d["rows"], 1):
        L.append(f"| {i} | {c.category} | {_md(_loc(c.old_page, c.old_section))} | {_md(_loc(c.new_page, c.new_section))} | {_md(c.match_method)} | "
                 f"{'' if c.confidence is None else f'{c.confidence:.2f}'} | {_md(', '.join(c.flags or []))} |")
    L += ["", "## Detailed changes", ""]
    for i, c in enumerate(d["rows"], 1):
        L += [f"### {i}. {c.category} — old {_md(_loc(c.old_page, c.old_section))} → new {_md(_loc(c.new_page, c.new_section))}", "",
              f"*Why:* {_mdt(c.explanation)}", ""]
        if c.old_text: L += [f"**{_md(comp.label_a)} (old):**", "", f"> {_mdt(_s(c.old_text, 1500))}", ""]
        if c.new_text: L += [f"**{_md(comp.label_b)} (new):**", "", f"> {_mdt(_s(c.new_text, 1500))}", ""]
        if c.ai_explanation:
            ai = c.ai_explanation
            L += [f"**AI interpretation** *(model: {_md(ai.get('model'))}; not verified)*", "", f"- Observed: {_mdt(ai.get('observed_change'))}",
                  f"- Possible implications (inference): {_mdt(ai.get('possible_implications') or '—')}", f"- Caveats: {_mdt(ai.get('caveats') or '—')}", ""]
    L += ["## Unresolved items", ""]
    L += [f"- {c.category} at old {_md(_loc(c.old_page, c.old_section))} / new {_md(_loc(c.new_page, c.new_section))} — {_mdt(_s(c.explanation, 200))}" for c in d["pending"]] or ["- None."]
    L += ["", "## Comparison limitations", ""] + [f"- {_mdt(x)}" for x in d["limits"]]
    return "\n".join(L) + "\n"


