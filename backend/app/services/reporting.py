def _spans(spans, tag) -> str:
    return "".join(html.escape(t) if op == "eq" else f"<{tag}>{html.escape(t)}</{tag}>" for op, t in spans)


def to_html(d: dict) -> str:
    comp, e = d["comp"], html.escape
    out = [f"<!doctype html><html lang=en><meta charset=utf-8><title>DocuDiff report</title><style>{_CSS}</style><body>",
           "<h1>DocuDiff Comparison Report</h1>",
           f"<p><small>Generated {d['generated']} · comparison <code>{comp.id}</code> · direction <b>{e(comp.label_a)} → {e(comp.label_b)}</b></small></p>",
           f"<h2>Executive summary</h2><p>{e(_summary(d))}</p><p class=note>Findings below are deterministic text comparisons. Sections marked “AI interpretation” are model-generated and unverified.</p>",
           "<h2>Documents</h2><table><tr><th></th><th>File</th><th>Pages</th><th>SHA-256</th></tr>"
           f"<tr><td>{e(comp.label_a)}</td><td>{e(d['a'].original_name)}</td><td>{d['a'].page_count}</td><td><code>{d['a'].sha256[:16]}…</code></td></tr>"
           f"<tr><td>{e(comp.label_b)}</td><td>{e(d['b'].original_name)}</td><td>{d['b'].page_count}</td><td><code>{d['b'].sha256[:16]}…</code></td></tr></table>",
           "<h2>Change table</h2><table><tr><th>#</th><th>Category</th><th>Old</th><th>New</th><th>Method</th><th>Conf.</th><th>Flags</th></tr>"]
    for i, c in enumerate(d["rows"], 1):
        out.append(f"<tr><td>{i}</td><td><span class='tag {c.category}'>{c.category}</span></td><td>{e(_loc(c.old_page, c.old_section))}</td><td>{e(_loc(c.new_page, c.new_section))}</td>"
                   f"<td>{e(str(c.match_method))}</td><td>{'' if c.confidence is None else f'{c.confidence:.2f}'}</td><td>{e(', '.join(c.flags or []))}</td></tr>")
    out.append("</table><h2>Detailed changes</h2>")
    for i, c in enumerate(d["rows"], 1):
        old = _spans(c.inline_diff["old"], "del") if c.inline_diff else e(_s(c.old_text, 1500))
        new = _spans(c.inline_diff["new"], "ins") if c.inline_diff else e(_s(c.new_text, 1500))
        out.append(f"<div class=card><b>{i}.</b> <span class='tag {c.category}'>{c.category}</span> old {e(_loc(c.old_page, c.old_section))} → new {e(_loc(c.new_page, c.new_section))}"
                   f"<p><i>Why:</i> {e(c.explanation)}</p>")
        if c.old_text: out.append(f"<b>{e(comp.label_a)} (old)</b><blockquote>{old}</blockquote>")
        if c.new_text: out.append(f"<b>{e(comp.label_b)} (new)</b><blockquote>{new}</blockquote>")
        if c.ai_explanation:
            ai = c.ai_explanation
            out.append(f"<div class=ai><b>AI interpretation</b> <small>(model {e(str(ai.get('model')))}; unverified)</small><br>Observed: {e(str(ai.get('observed_change')))}"
                       f"<br>Possible implications (inference): {e(str(ai.get('possible_implications') or '—'))}<br>Caveats: {e(str(ai.get('caveats') or '—'))}</div>")
        out.append("</div>")
    out.append("<h2>Unresolved items</h2><ul>" + ("".join(f"<li>{c.category} old {e(_loc(c.old_page, c.old_section))} / new {e(_loc(c.new_page, c.new_section))} — {e(_s(c.explanation, 200))}</li>" for c in d["pending"]) or "<li>None.</li>") + "</ul>")
    out.append("<h2>Comparison limitations</h2><ul>" + "".join(f"<li>{e(x)}</li>" for x in d["limits"]) + "</ul></body></html>")
    return "".join(out)


_SUP = "/System/Library/Fonts/Supplemental/"
# (regular, bold, italic[, subfont indexes]) – first complete set that covers every needed glyph wins, else the best coverage.
_FONT_CANDIDATES: list[tuple] = [
    ("/Library/Fonts/Arial Unicode.ttf",) * 3,                      # macOS: broad coverage but no U+20B9 (rupee)
    (_SUP + "Arial Unicode.ttf",) * 3,
    ("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Oblique.ttf"),
    ("/usr/share/fonts/dejavu/DejaVuSans.ttf", "/usr/share/fonts/dejavu/DejaVuSans-Bold.ttf", "/usr/share/fonts/dejavu/DejaVuSans-Oblique.ttf"),
    ("/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf", "/usr/share/fonts/truetype/noto/NotoSans-Bold.ttf", "/usr/share/fonts/truetype/noto/NotoSans-Italic.ttf"),
    ("/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf", "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf", "/usr/share/fonts/truetype/liberation/LiberationSans-Italic.ttf"),
    (_SUP + "Baskerville.ttc",) * 3 + ((0, 1, 2),),                 # macOS fonts verified to contain U+20B9 (as .ttc subfonts)
    (_SUP + "Cochin.ttc",) * 3 + ((0, 1, 2),),
    (_SUP + "Marion.ttc",) * 3 + ((0, 2, 1),),
]
_FALLBACK_SUBS = {"₹": "Rs.", "→": "->"}
_font_cache: dict[tuple, tuple] = {}


def _non_latin1(texts) -> set[str]:
    out: set[str] = set()
    for t in texts:
        for ch in (t or ""):
            if ord(ch) > 127:
                try:
                    ch.encode("cp1252")
                except UnicodeEncodeError:
                    out.add(ch)
    return out


def _needed_chars(d: dict) -> set[str]:
    texts = [d["comp"].label_a, d["comp"].label_b, d["a"].original_name, d["b"].original_name, *d["limits"]]
    for c in d["rows"] + d["pending"]:
        texts += [c.old_text, c.new_text, c.explanation, c.old_section, c.new_section]
        if c.ai_explanation:
            texts += [str(v) for v in c.ai_explanation.values()]
    return _non_latin1(texts)


def _needs_unicode(d: dict) -> bool:
    return bool(_needed_chars(d) - {"→"})


def _fc_candidates(ch: str) -> list[tuple]:
    """Extra candidates from fontconfig (`fc-list ':charset=XXXX'`) when installed: plain .ttf files only."""
    import shutil
    import subprocess
    if not shutil.which("fc-list"):
        return []
    try:
        out = subprocess.run(["fc-list", f":charset={ord(ch):x}", "file"], capture_output=True, text=True, timeout=5).stdout
    except Exception:  # noqa: BLE001
        return []
    files = sorted({ln.split(":")[0].strip() for ln in out.splitlines() if ln.strip().lower().split(":")[0].endswith(".ttf")})
    return [(f, f, f) for f in files[:8]]


def _load_family(cand: tuple):
    """Register candidate fonts; returns (reg, bold, ital, coverage) or None. Coverage is the set of code points of the regular face."""
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    paths, idx = cand[:3], (cand[3] if len(cand) > 3 else (None, None, None))
    if not all(Path(q).is_file() for q in paths):
        return None
    key = (paths, idx)
    if key in _font_cache:
        return _font_cache[key]
    try:
        tag = f"DD{len(_font_cache)}"
        faces = []
        for suffix, q, i in zip(("", "-B", "-I"), paths, idx):
            name = tag + suffix
            pdfmetrics.registerFont(TTFont(name, q, subfontIndex=i or 0))
            faces.append(name)
        pdfmetrics.registerFontFamily(tag, normal=faces[0], bold=faces[1], italic=faces[2], boldItalic=faces[1])
        cov = set(pdfmetrics.getFont(faces[0]).face.charToGlyph)
        res = (*faces, cov)
    except Exception:  # noqa: BLE001 - unreadable font: skip
        res = None
    _font_cache[key] = res
    return res


def _pdf_font(needed: set[str]):
    """Return (regular, bold, italic, unicode_ok, covered). Built-in Helvetica only covers WinAnsi, so e.g. ₹, Devanagari or CJK
    would otherwise be drawn as wrong glyphs. `covered` is the set of `needed` characters the chosen font can really draw."""
    want = needed - {"→"}
    if not want:
        return "Helvetica", "Helvetica-Bold", "Helvetica-Oblique", False, set()
    cands = list(_FONT_CANDIDATES)
    for ch in sorted(want)[:1]:
        cands += _fc_candidates(ch)
    best, best_n = None, 0
    for cand in cands:
        fam = _load_family(cand)
        if not fam:
            continue
        n = sum(1 for ch in want if ord(ch) in fam[3])
        if n == len(want):
            best = fam
            break
        if n > best_n:
            best, best_n = fam, n
    if best is None:
        return "Helvetica", "Helvetica-Bold", "Helvetica-Oblique", False, set()
    return best[0], best[1], best[2], True, {ch for ch in want | {"→"} if ord(ch) in best[3]}


def _substitute(t: str, covered: set[str], uni: bool, stats: dict) -> str:
    """Replace characters the chosen font cannot draw: known substitutes (₹ -> Rs., → -> ->) or a visible '?'.
    Never emit a glyph the font lacks (that would render as an empty box)."""
    out = []
    for ch in t:
        if ord(ch) < 128:
            out.append(ch); continue
        try:
            ch.encode("cp1252")
            ok = True   # Latin-1/WinAnsi: drawn by Helvetica, and every Unicode candidate covers it
        except UnicodeEncodeError:
            ok = uni and ch in covered
        if ok:
            out.append(ch)
        elif ch in _FALLBACK_SUBS:
            out.append(_FALLBACK_SUBS[ch])
            if ch != "→":
                stats.setdefault("subs", set()).add(ch)
        else:
            out.append("?"); stats["lost"] = stats.get("lost", 0) + 1
    return "".join(out)


def to_pdf(d: dict, path: Path) -> None:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
    from xml.sax.saxutils import escape as esc

    reg, bold, ital, uni, covered = _pdf_font(_needed_chars(d))
    stats: dict = {}
    st = getSampleStyleSheet()
    for n in ("Title", "Heading2", "Heading4", "BodyText", "Italic", "Normal"):
        base = st[n]
        base.fontName = bold if n in ("Title", "Heading2", "Heading4") else ital if n == "Italic" else reg
    cell = ParagraphStyle("cell", parent=st["BodyText"], fontSize=8, leading=10, spaceBefore=0, spaceAfter=0)
    cellh = ParagraphStyle("cellh", parent=cell, fontName=bold)
    st["BodyText"].wordWrap = "CJK"  # allow breaking anywhere so unbroken tokens (hashes, URLs) never overflow the margins
    cell.wordWrap = "CJK"

    def x(t: object) -> str:
        t = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f]", "", str(t if t is not None else ""))
        return esc(_substitute(t, covered, uni, stats))

    doc = SimpleDocTemplate(str(path), pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=16 * mm, title="DocuDiff report")
    comp, f = d["comp"], []
    P = lambda t, s="BodyText": f.append(Paragraph(t, st[s]))  # noqa: E731
    P("DocuDiff Comparison Report", "Title")
    P(f"Generated {d['generated']} · comparison {comp.id} · {x(comp.label_a)} → {x(comp.label_b)}")
    P("Executive summary", "Heading2"); P(x(_summary(d)))
    P("Findings are deterministic text comparisons; AI interpretations are labelled and unverified.", "Italic")

    def table(rows, widths):
        t = Table([[Paragraph(v, cellh if r == 0 else cell) for v in row] for r, row in enumerate(rows)], colWidths=widths, repeatRows=1)
        t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#b6c4bb")), ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f3f6f4")), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
        f.append(t); f.append(Spacer(1, 6))

    W = A4[0] - 36 * mm
    P("Documents", "Heading2")
    table([["", "File", "Pages", "SHA-256"],
           [x(comp.label_a), x(d["a"].original_name), str(d["a"].page_count), d["a"].sha256[:16] + "…"],
           [x(comp.label_b), x(d["b"].original_name), str(d["b"].page_count), d["b"].sha256[:16] + "…"]], [W * .2, W * .4, W * .1, W * .3])
    P("Change table", "Heading2")
    if d["rows"]:
        table([["#", "Category", "Old", "New", "Method", "Conf.", "Flags"]] +
              [[str(i), c.category, x(_loc(c.old_page, c.old_section)), x(_loc(c.new_page, c.new_section)), x(c.match_method),
                "" if c.confidence is None else f"{c.confidence:.2f}", x(", ".join(c.flags or []))] for i, c in enumerate(d["rows"], 1)],
              [W * .05, W * .15, W * .2, W * .2, W * .1, W * .07, W * .23])
    else:
        P("No changes to report.")
    P("Detailed changes", "Heading2")
    for i, c in enumerate(d["rows"], 1):
        P(f"<b>{i}. {c.category}</b> — old {x(_loc(c.old_page, c.old_section))} → new {x(_loc(c.new_page, c.new_section))}", "Heading4")
        P(f"<i>Why:</i> {x(c.explanation)}")
        if c.old_text: P(f"<b>Old:</b> {x(_s(c.old_text, 1500))}")
        if c.new_text: P(f"<b>New:</b> {x(_s(c.new_text, 1500))}")
        if c.ai_explanation:
            ai = c.ai_explanation
            P(f"<b>AI interpretation (unverified; model {x(ai.get('model'))}):</b> {x(ai.get('observed_change'))}")
            if ai.get("possible_implications"): P(f"<i>Possible implications (inference):</i> {x(ai['possible_implications'])}")
            if ai.get("caveats"): P(f"<i>Caveats:</i> {x(ai['caveats'])}")
        f.append(Spacer(1, 4))
    P("Unresolved items", "Heading2")
    for c in d["pending"] or []: P("• " + x(_s(c.explanation, 200)))
    if not d["pending"]: P("None.")
    limits = list(d["limits"])
    if "₹" in stats.get("subs", ()):
        limits.append("No installed font on the server contains the rupee sign (U+20B9), so it is printed as 'Rs.' in this PDF. The HTML and Markdown exports contain the original text.")
    if stats.get("lost"):
        limits.append(f"This PDF could not draw {stats['lost']} character(s) that no installed font covers (shown as '?'). The HTML and Markdown exports contain the original text.")
    P("Comparison limitations", "Heading2")
    for l in limits: P("• " + x(l))
    doc.build(f)
